/**
 * Gr3y Tools - Export Pairing Relay
 *
 * A short-lived, one-time relay between Export-InstalledApps.ps1 (running on a machine
 * with no GUI access) and Gr3ysUtilities.ps1's "Pair with Old Machine..." dialog (running
 * on the machine doing the comparison). Nothing is ever persisted beyond the KV entry's
 * own TTL - if the GUI isn't actively polling for a given code, the data it receives is
 * simply discarded once read (or expires unread).
 *
 * Deploy: Cloudflare dashboard -> Workers & Pages -> Create Worker -> paste this file's
 * contents -> Deploy. Then create a KV namespace (Workers & Pages -> KV -> Create) and
 * bind it to this Worker as EXPORT_RELAY_KV (Worker -> Settings -> Variables -> KV
 * Namespace Bindings). No custom domain/route needed - the default *.workers.dev URL is
 * all Export-InstalledApps.ps1 and Gr3ysUtilities.ps1 need to be configured with.
 *
 * Routes:
 *   POST /submit?code=XXXXXX   body: the export JSON (from Export-InstalledApps.ps1)
 *   GET  /poll?code=XXXXXX     returns the stored JSON once, then deletes it (404 if
 *                              nothing is stored yet under that code - keep polling)
 */

const CODE_PATTERN = /^[A-Z0-9]{4,10}$/;
const TTL_SECONDS = 600; // 10 minutes - matches the GUI's own polling timeout
const MAX_BODY_BYTES = 1024 * 1024; // 1MB - generous for an installed-apps export, not open-ended

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const code = (url.searchParams.get('code') || '').toUpperCase();

    if (!CODE_PATTERN.test(code)) {
      return new Response('Invalid or missing code', { status: 400 });
    }

    if (url.pathname === '/submit' && request.method === 'POST') {
      const body = await request.text();
      if (!body || body.length > MAX_BODY_BYTES) {
        return new Response('Body missing or too large', { status: 400 });
      }
      // No existence check before writing - codes are short-lived and randomly
      // generated by the GUI, so an overwrite would only happen if two exports
      // raced on the exact same code, which the GUI never reuses within its TTL.
      await env.EXPORT_RELAY_KV.put(`code:${code}`, body, { expirationTtl: TTL_SECONDS });
      return new Response('OK', { status: 200 });
    }

    if (url.pathname === '/poll' && request.method === 'GET') {
      const key = `code:${code}`;
      const data = await env.EXPORT_RELAY_KV.get(key);
      if (data === null) {
        return new Response('Not found', { status: 404 });
      }
      // Claim it - a poll that successfully reads data also consumes it, so a second
      // poll for the same code (another tab, a retry after a slow response) gets 404
      // instead of silently handing out the same export twice.
      await env.EXPORT_RELAY_KV.delete(key);
      return new Response(data, { status: 200, headers: { 'Content-Type': 'application/json' } });
    }

    return new Response('Not found', { status: 404 });
  },
};
